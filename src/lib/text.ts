/**
 * متن‌یار جست‌وجوی فارسی
 * ------------------------------------------------------------------
 * کاربر معمولاً «مطالبه» را بدون نیم‌فاصله، یا واژه را با حرف عربی
 * (ی و ک عربی) یا با نیم‌فاصلۀ جاافتاده می‌نویسد. مقایسۀ خام، نتیجه را صفر می‌کند.
 * این ماژول هر دو سو (متن مقاله و عبارت جست‌وجو) را به یک شکل یکسان
 * می‌برد تا جست‌وجو طبیعی رفتار کند:
 *  ۱. حروف عربی (ی و ک با کد نقطۀ عربی) به «ی» و «ک» فارسی تبدیل می‌شوند؛
 *  ۲. اعراب و تشدید حذف می‌شوند؛
 *  ۳. نیم‌فاصله (ZWNJ) و فاصلۀ مجازی حذف می‌شوند تا «نیم‌فاصله» و
 *     «نیم فاصله» یکسان دیده شوند؛
 *  ۴. ارقام فارسی و عربی به لاتین تبدیل می‌شوند تا «مادۀ ۳» با «ماده 3»
 *     یکی باشد.
 */

const ARABIC_TO_PERSIAN: Record<string, string> = {
  "\u064A": "\u06CC",
  "\u0649": "\u06CC",
  "\u0643": "\u06A9",
  "\u06C0": "\u0647",
  "\u0629": "\u0647",
  "\u0623": "\u0627",
  "\u0625": "\u0627",
  "\u0622": "\u0627",
  "\u0671": "\u0627",
  "\u0624": "\u0648",
};

/* اعراب، تشدید، همزۀ ترکیبی (مثل «ۀ» تجزیه‌شده) و کشیدۀ فارسی */
const DIACRITICS = /[\u064B-\u065F\u0670\u0640]/g;
const ZERO_WIDTH = /[\u200B-\u200F\u202A-\u202E\uFEFF]/g;

const DIGIT_MAP: Record<string, string> = {
  "۰": "0",
  "۱": "1",
  "۲": "2",
  "۳": "3",
  "۴": "4",
  "۵": "5",
  "۶": "6",
  "۷": "7",
  "۸": "8",
  "۹": "9",
  "٠": "0",
  "١": "1",
  "٢": "2",
  "٣": "3",
  "٤": "4",
  "٥": "5",
  "٦": "6",
  "٧": "7",
  "٨": "8",
  "٩": "9",
};

/** یکدست‌سازی متن برای مقایسه و جست‌وجو */
export function normalizeFa(input: string): string {
  return input
    .replace(/[\u064A\u0649\u0643\u06C0\u0629\u0623\u0625\u0622\u0671\u0624]/g, (char) => ARABIC_TO_PERSIAN[char] ?? char)
    .replace(DIACRITICS, "")
    /* نیم‌فاصله به فاصله تبدیل می‌شود تا «نیم‌فاصله» و «نیم فاصله» یکی شوند */
    .replace(/[\u200C\u200D]/g, " ")
    .replace(ZERO_WIDTH, "")
    .replace(/[۰-۹٠-٩]/g, (digit) => DIGIT_MAP[digit] ?? digit)
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

/** تبدیل عبارت کاربر به واژه‌های قابل جست‌وجو */
export function searchTerms(query: string): string[] {
  return normalizeFa(query)
    .split(/[\s،,.:;؛·\-—/()]+/)
    .map((term) => term.trim())
    .filter((term) => term.length > 0);
}

/** آیا همۀ واژه‌های جست‌وجو در متن هستند؟ (ترتیب مهم نیست) */
export function matchesAll(haystack: string, terms: string[]): boolean {
  if (terms.length === 0) return true;
  return terms.every((term) => haystack.includes(term));
}
